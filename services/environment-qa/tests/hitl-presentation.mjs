vm.runInContext(escaping + helpers, context);
const present = interaction => context.interactionPresentation(interaction, 100);
const profiles = [{id:'k3-non-hitl'}, {id:'tbench-hitl'}, {id:'tbench-non-hitl'}];
assert.equal(context.chooseLaunchProfile(profiles, 'hitl'), 'tbench-hitl');
assert.equal(context.chooseLaunchProfile(profiles, null), 'tbench-non-hitl');
assert.equal(context.chooseLaunchProfile([{id:'k3-non-hitl'}], 'hitl'), 'legacy');
