assert.equal(present({type:'review', allowed:[]}).decisions.length, 0);
assert.equal(present({type:'review', expires_at:100}).expired, true);
assert.equal(present({type:'review', expires_at:99}).decisions.length, 0);
assert.equal(present({type:'permission', allowed:['confirm']}).decisions.length, 0);
assert.equal(present({type:'permission'}).title, 'Tool permission required');
const permission = {type:'permission', response_contract:'environment-qa.permission.v1', allowed:['once','reject','confirm']};
assert.equal(present(permission).decisions.join(), 'once,reject');
assert.match(present(permission).message, /only the displayed tool request/);
assert.equal(present({...permission, expires_at:99}).decisions.length, 0);
