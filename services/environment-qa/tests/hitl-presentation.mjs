import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const source = readFileSync(new URL('../web/app.js', import.meta.url), 'utf8');
const escaping = source.slice(source.indexOf('const escapeHtml ='), source.indexOf('async function api'));
const helpers = source.slice(source.indexOf('function interactionPresentation'), source.indexOf('let inspectedGate'));
